// Command landmask writes internal/handler/hack_land.go, the land of the Hack
// theme's map in cells of one degree, from Natural Earth's land or countries
// shapefile at 1:110m (public domain, naturalearthdata.com):
//
//	go run ./scripts/landmask path/to/ne_110m_land.shp > internal/handler/hack_land.go
//
// A cell is land when its centre is inside a polygon. Run it again only when
// the map should follow newer coastlines.
package main

import (
	"encoding/binary"
	"fmt"
	"go/format"
	"io"
	"math"
	"os"
	"strings"
)

const (
	// topLat and bottomLat bound the rows: nobody's exit is further north or
	// south.
	topLat    = 72
	bottomLat = -56
	// polygonShape is the shapefile type of a polygon record.
	polygonShape = 5
	// headerSize is the shapefile's file header; recordHeader a record's.
	headerSize   = 100
	recordHeader = 8
)

type point struct{ x, y float64 }

type ring struct {
	points                 []point
	minX, minY, maxX, maxY float64
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: landmask <shapefile.shp>")
		os.Exit(2)
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, "read shapefile:", err)
		os.Exit(1)
	}
	rings, err := readRings(data)
	if err != nil {
		fmt.Fprintln(os.Stderr, "parse shapefile:", os.Args[1], err)
		os.Exit(1)
	}
	if err := write(os.Stdout, rows(rings)); err != nil {
		fmt.Fprintln(os.Stderr, "write:", err)
		os.Exit(1)
	}
}

// readRings is every ring of every polygon record of a shapefile.
func readRings(data []byte) ([]ring, error) {
	if len(data) < headerSize {
		return nil, fmt.Errorf("file of %d bytes is shorter than its header", len(data))
	}
	var rings []ring
	for offset := headerSize; offset+recordHeader <= len(data); {
		length := int(binary.BigEndian.Uint32(data[offset+4:])) * 2
		content := data[offset+recordHeader : offset+recordHeader+length]
		offset += recordHeader + length
		if binary.LittleEndian.Uint32(content) != polygonShape {
			continue
		}
		parts := int(binary.LittleEndian.Uint32(content[36:]))
		total := int(binary.LittleEndian.Uint32(content[40:]))
		starts := make([]int, parts+1)
		for i := range parts {
			starts[i] = int(binary.LittleEndian.Uint32(content[44+4*i:]))
		}
		starts[parts] = total
		base := 44 + 4*parts
		for i := range parts {
			r := ring{minX: math.Inf(1), minY: math.Inf(1), maxX: math.Inf(-1), maxY: math.Inf(-1)}
			for j := starts[i]; j < starts[i+1]; j++ {
				x := math.Float64frombits(binary.LittleEndian.Uint64(content[base+16*j:]))
				y := math.Float64frombits(binary.LittleEndian.Uint64(content[base+16*j+8:]))
				r.points = append(r.points, point{x, y})
				r.minX, r.minY, r.maxX, r.maxY = min(r.minX, x), min(r.minY, y), max(r.maxX, x), max(r.maxY, y)
			}
			rings = append(rings, r)
		}
	}
	if len(rings) == 0 {
		return nil, fmt.Errorf("no polygon records")
	}
	return rings, nil
}

// inside says p is inside an odd number of rings: land, holes left out.
func inside(rings []ring, p point) bool {
	in := false
	for _, r := range rings {
		if p.x < r.minX || p.x > r.maxX || p.y < r.minY || p.y > r.maxY {
			continue
		}
		for i, j := 0, len(r.points)-1; i < len(r.points); j, i = i, i+1 {
			a, b := r.points[i], r.points[j]
			if (a.y > p.y) != (b.y > p.y) && p.x < (b.x-a.x)*(p.y-a.y)/(b.y-a.y)+a.x {
				in = !in
			}
		}
	}
	return in
}

// rows is, for each degree of latitude from topLat down, the runs of land
// columns, counted east from 180 degrees west.
func rows(rings []ring) [][][2]int {
	var out [][][2]int
	for lat := topLat; lat > bottomLat; lat-- {
		var runs [][2]int
		start := -1
		for col := 0; col <= 360; col++ {
			land := col < 360 && inside(rings, point{float64(col) - 180 + 0.5, float64(lat) - 0.5})
			switch {
			case land && start < 0:
				start = col
			case !land && start >= 0:
				runs = append(runs, [2]int{start, col - 1})
				start = -1
			}
		}
		out = append(out, runs)
	}
	return out
}

// write prints the rows as the formatted Go source of hack_land.go.
func write(w io.Writer, land [][][2]int) error {
	var b strings.Builder
	b.WriteString("// Code generated by scripts/landmask from Natural Earth (public domain). DO NOT EDIT.\n\n")
	b.WriteString("package handler\n\n")
	fmt.Fprintf(&b, "// hackLandTop is the latitude hackLand's first row starts at; each row is\n// one degree further south.\nconst hackLandTop = %d\n\n", topLat)
	b.WriteString("// hackLand lists, for each degree of latitude, the runs of columns of one\n// degree (inclusive, counted east from 180 degrees west) that hold land.\n")
	b.WriteString("var hackLand = [][][2]int{\n")
	for i, runs := range land {
		b.WriteString("\t{")
		for k, r := range runs {
			if k > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "{%d, %d}", r[0], r[1])
		}
		fmt.Fprintf(&b, "}, // %d\n", topLat-i)
	}
	b.WriteString("}\n")
	source, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("format source: %w", err)
	}
	_, err = w.Write(source)
	return err
}
